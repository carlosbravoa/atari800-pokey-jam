"""Styles for the generator: all the musical knowledge lives here, as data.

A style:
  beat        (lo, hi) frames per beat -> tempo is picked per tune (3600/beat bpm)
  swing       ticks the off-beat eighth is late (12-tick beat; 2 = triplet feel)
  keys        tonic pitch classes to pick from (0 = C)
  forms       chord forms: bars separated by |, several chords split a bar;
              optional head plan: a phrase letter per `unit` bars (AABA...)
  riffs       the riff bank, in chord-scale degrees (see gen.parse_riff)
  lead        range, presets (stable pure-tone sounds only: SYNTH's buzz +
              glide, CHIPARP's fixed-shape arpeggio and LASER's sweep ruin a
              line -- keep them out of every pool), gap (release before the next note), snap
              (1: notes on beats 1/3 land on chord tones, 2: every beat;
              default 2), key_scale (riffs read in
              one scale on the key instead of per chord: Ballblazer's way)
  bass/comp   range, presets, pattern banks: (tick, ticks, code)
  drums       16-step patterns per drum: x = always, 1-9 = 10-90 %, . = never;
              split: a repeat within two 16ths moves to the other POKEY
  mix         volume cap per track [lead, bass, comp1, comp2], 0 = full
  sections    per section: bars (default = the form), lead variation odds,
              bass/comp/drum pattern kinds
  arrangements  section orders; one is picked per tune

Bass codes: R root, 5 fifth above, L fifth below, 8 octave, 3 third,
7 seventh, A approach to the next chord's root, S scale tone; an int is
semitones above the root. Comp codes: '2' both voices, '1' lower only,
'arp' a 16th arpeggio over the voicing.
"""

